def clean_text(text):
    # 1. Ensure it's a string (handles empty cells)
    text = str(text)

    # 2. Lowercase: Normalizes "Bad" and "bad" to the same word
    text = text.lower()

    # 3. Demojize: Converts emojis to text (e.g., 😡 -> :pouting_face:)
    text = emoji.demojize(text)

    # 4. Spacing: Replaces ":" with space so "face" doesn't get stuck to "pouting"
    text = text.replace(":", " ")

    # 5. Fix Elongation: Reduces "sooooo" to "soo" (max 2 repeated chars)
    #    (Crucial for social media slang)
    text = re.sub(r'(.)\1{2,}', r'\1\1', text)

    return text

